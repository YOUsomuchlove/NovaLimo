import { palette } from './palette';
import { fontFamily, fontSize, motion, radius, zIndex } from './scales';
import { type SemanticTheme, darkTheme, lightTheme } from './semantic';

const kebab = (s: string) =>
  s
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .replace(/([a-z])([0-9])/g, '$1-$2')
    .toLowerCase();

/** Flatten a semantic theme into `--nl-*` custom properties. */
function themeVars(theme: SemanticTheme): string[] {
  const out: string[] = [];
  for (const [key, value] of Object.entries(theme)) {
    if (typeof value === 'string') {
      out.push(`  --nl-${kebab(key)}: ${value};`);
    } else {
      for (const [part, v] of Object.entries(value as Record<string, string>)) {
        out.push(`  --nl-${kebab(key)}-${part}: ${v};`);
      }
    }
  }
  return out;
}

/** Tailwind colour utilities that point at the runtime theme variables. */
function semanticColorUtilities(): string[] {
  const out: string[] = [];
  for (const [key, value] of Object.entries(darkTheme)) {
    if (key.startsWith('shadow')) continue;
    const name = kebab(key);
    if (typeof value === 'string') {
      out.push(`  --color-${name}: var(--nl-${name});`);
    } else {
      for (const part of Object.keys(value)) {
        out.push(`  --color-${name}-${part}: var(--nl-${name}-${part});`);
      }
    }
  }
  return out;
}

function paletteUtilities(): string[] {
  const out: string[] = [];
  for (const [family, shades] of Object.entries(palette)) {
    if (typeof shades === 'string') continue;
    for (const [shade, hex] of Object.entries(shades)) {
      out.push(`  --color-${family}-${shade}: ${hex};`);
    }
  }
  return out;
}

/**
 * Builds `libs/design-tokens/src/generated/tokens.css`.
 *
 * - `:root` / `[data-theme='dark']` / `[data-theme='light']` hold runtime `--nl-*` variables,
 *   so any subtree can switch theme with a `data-theme` attribute.
 * - `@theme inline` registers Tailwind v4 utilities (`bg-surface-1`, `text-fg-muted`,
 *   `border-border-subtle`, `rounded-card`, `shadow-e2`, `text-ui`, `ease-nova`…).
 */
export function generateTokensCss(): string {
  const lines: string[] = [
    '/* AUTO-GENERATED by `nx run design-tokens:generate` — do not edit by hand. */',
    '/* Source: libs/design-tokens/src/lib/*.ts */',
    '',
    ":root,\n[data-theme='dark'] {",
    '  color-scheme: dark;',
    ...themeVars(darkTheme),
    '}',
    '',
    "[data-theme='light'] {",
    '  color-scheme: light;',
    ...themeVars(lightTheme),
    '}',
    '',
    '@theme inline {',
    `  --font-sans: ${fontFamily.sans};`,
    `  --font-mono: ${fontFamily.mono};`,
    '',
    ...semanticColorUtilities(),
    '',
    ...paletteUtilities(),
    '',
    ...Object.entries(radius).map(([k, v]) => `  --radius-${k}: ${v}px;`),
    '',
    '  --shadow-e1: var(--nl-shadow-e1);',
    '  --shadow-e2: var(--nl-shadow-e2);',
    '  --shadow-e3: var(--nl-shadow-e3);',
    '  --shadow-brand: var(--nl-shadow-brand);',
    '',
    `  --text-ui: ${fontSize.ui.size / 16}rem;`,
    `  --text-ui--line-height: ${fontSize.ui.lineHeight / fontSize.ui.size};`,
    `  --text-display: ${fontSize.display.size / 16}rem;`,
    `  --text-display--line-height: ${fontSize.display.lineHeight / fontSize.display.size};`,
    '',
    `  --ease-nova: ${motion.easing};`,
    '}',
    '',
    ':root {',
    ...Object.entries(zIndex).map(([k, v]) => `  --nl-z-${k}: ${v};`),
    `  --nl-duration-fast: ${motion.duration.fast}ms;`,
    `  --nl-duration-base: ${motion.duration.base}ms;`,
    `  --nl-duration-slow: ${motion.duration.slow}ms;`,
    '}',
    '',
  ];
  return lines.join('\n');
}
