import {
  type ThemeName,
  alpha,
  fontFamily,
  motion,
  palette,
  radius,
  themes,
} from '@limousine-workspace/design-tokens';
import { type ThemeConfig, theme as antdTheme } from 'antd';

/**
 * antd theme generated from design tokens — replaces the old light admin theme that every
 * dark page had to fight with `!important` Tailwind overrides.
 */
export function createAntdTheme(mode: ThemeName = 'dark'): ThemeConfig {
  const t = themes[mode];
  const dark = mode === 'dark';

  return {
    algorithm: dark ? antdTheme.darkAlgorithm : antdTheme.defaultAlgorithm,
    cssVar: { key: `nl-${mode}` },
    hashed: false,
    token: {
      colorPrimary: t.brand,
      colorInfo: t.info.solid,
      colorSuccess: t.success.solid,
      colorWarning: t.warning.solid,
      colorError: t.danger.solid,
      colorLink: t.brandFg,
      colorLinkHover: t.brandHover,

      colorBgBase: t.canvas,
      colorBgLayout: t.canvas,
      colorBgContainer: t.surface1,
      colorBgElevated: t.surface2,
      colorBgSpotlight: t.surface3,
      colorBgMask: t.scrim,

      colorBorder: t.borderDefault,
      colorBorderSecondary: t.borderSubtle,
      colorSplit: t.borderSubtle,

      colorText: t.fg,
      colorTextSecondary: t.fgSecondary,
      colorTextTertiary: t.fgMuted,
      colorTextQuaternary: t.fgDisabled,
      colorTextPlaceholder: t.fgDisabled,
      colorTextLightSolid: t.onBrand,

      fontFamily: fontFamily.sans,
      fontSize: 14,
      borderRadius: radius.control,
      borderRadiusLG: radius.card,
      borderRadiusSM: radius.tag,
      borderRadiusXS: 4,
      controlHeight: 40,
      controlHeightLG: 48,
      controlHeightSM: 32,
      controlOutline: t.focusRing,
      boxShadow: t.shadowE2,
      boxShadowSecondary: t.shadowE3,
      motionEaseOut: motion.easing,
      wireframe: false,
    },
    components: {
      Button: {
        fontWeight: 600,
        primaryShadow: t.shadowBrand,
        defaultShadow: 'none',
        dangerShadow: 'none',
        defaultBg: t.surface3,
        defaultBorderColor: t.borderDefault,
        defaultColor: t.fg,
        defaultHoverBg: t.surface2,
        defaultHoverBorderColor: t.borderStrong,
        defaultHoverColor: t.fg,
      },
      Input: {
        activeBorderColor: t.brand,
        hoverBorderColor: t.borderStrong,
        activeShadow: `0 0 0 4px ${t.brandSubtle}`,
        colorBgContainer: t.surface2,
      },
      InputNumber: {
        activeBorderColor: t.brand,
        hoverBorderColor: t.borderStrong,
        colorBgContainer: t.surface2,
      },
      Select: {
        colorBgContainer: t.surface2,
        optionSelectedBg: t.brandSubtle,
        optionSelectedColor: t.fg,
        optionActiveBg: t.surface3,
        activeBorderColor: t.brand,
        hoverBorderColor: t.borderStrong,
      },
      DatePicker: {
        colorBgContainer: t.surface2,
        activeBorderColor: t.brand,
        hoverBorderColor: t.borderStrong,
        cellActiveWithRangeBg: t.brandSubtle,
      },
      Table: {
        headerBg: t.surface2,
        headerColor: t.fgMuted,
        headerSplitColor: 'transparent',
        headerSortActiveBg: t.surface3,
        rowHoverBg: dark ? alpha(palette.gold[500], 0.04) : t.surface2,
        rowSelectedBg: t.brandSubtle,
        rowSelectedHoverBg: t.brandSubtle,
        borderColor: t.borderSubtle,
        cellPaddingBlock: 14,
        cellFontSize: 13,
        footerBg: t.surface1,
      },
      Tabs: {
        inkBarColor: t.brand,
        itemSelectedColor: t.fg,
        itemHoverColor: t.fg,
        itemColor: t.fgMuted,
        titleFontSize: 14,
      },
      Menu: {
        itemBg: 'transparent',
        subMenuItemBg: 'transparent',
        darkItemBg: 'transparent',
        darkSubMenuItemBg: 'transparent',
        itemSelectedBg: t.brandSubtle,
        itemSelectedColor: t.brandFg,
        darkItemSelectedBg: t.brandSubtle,
        darkItemSelectedColor: t.brandFg,
        itemHoverBg: t.surface2,
        darkItemHoverBg: t.surface2,
        itemColor: t.fgSecondary,
        darkItemColor: t.fgSecondary,
        itemBorderRadius: radius.control,
        itemHeight: 40,
        iconSize: 18,
      },
      Layout: {
        bodyBg: t.canvas,
        headerBg: t.surface1,
        siderBg: t.surface1,
        triggerBg: t.surface2,
        headerHeight: 64,
        headerPadding: '0 24px',
      },
      Modal: {
        contentBg: t.surface1,
        headerBg: t.surface1,
        footerBg: t.surface1,
        titleFontSize: 18,
      },
      Drawer: { colorBgElevated: t.surface1 },
      Card: { colorBgContainer: t.surface1, headerFontSize: 16 },
      Pagination: { itemActiveBg: t.brandSubtle, itemBg: 'transparent' },
      Tag: { defaultBg: t.surface3, defaultColor: t.fgSecondary },
      Tooltip: { colorBgSpotlight: t.surface3, colorTextLightSolid: t.fg },
      Steps: { colorPrimary: t.brand },
      Segmented: {
        trackBg: t.surface2,
        itemSelectedBg: t.surface1,
        itemSelectedColor: t.fg,
        itemColor: t.fgMuted,
      },
      Message: { contentBg: t.surface2 },
      Notification: { colorBgElevated: t.surface2 },
    },
  };
}
